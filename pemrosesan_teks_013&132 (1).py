"""Top Pasangan Judul Paling Mirip"""

def top_pairs(sim_matrix, titles, k=10):
    i, j = np.triu_indices_from(sim_matrix, k=1)   # segitiga atas, tanpa diagonal
    scores = sim_matrix[i, j]
    order = np.argsort(scores)[::-1][:k]
    return pd.DataFrame({
        'judul_1': titles.iloc[i[order]].values,
        'judul_2': titles.iloc[j[order]].values,
        'skor': scores[order].round(3)
    })

print('=== Top pasangan: Jaccard ===')
