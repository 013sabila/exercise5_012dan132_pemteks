import re

patterns = {
    'ada_titik_dua': r':',
    'ada_kurung': r'\(.*?\)',
    'ada_angka': r'\d',
    'ada_tanda_hubung': r' - ',
}
for name, pat in patterns.items():
    n = df['title'].str.contains(pat, regex=True).sum()
    print(f'{name}: {n} judul')

df[df['title'].str.contains(r':|\(', regex=True)]

def extract_series(title):
    m = re.search(r'\s*\(([^)]*)\)\s*$', title)
    if m:
        return title[:m.start()].strip(), m.group(1).strip()
    return title, None

df[['title_no_paren', 'series_info']] = df['title'].apply(
    lambda t: pd.Series(extract_series(t))
)

def split_title(title):
    if ':' in title:
        main, sub = title.split(':', 1)
        return main.strip(), sub.strip()
    return title.strip(), None

df[['main_title', 'subtitle']] = df['title_no_paren'].apply(
    lambda t: pd.Series(split_title(t))
)

version_pat = re.compile(
    r'(?:#|version\s*|vol(?:ume)?\.?\s*|book\s*|part\s*)(\d+)', re.IGNORECASE
)

def extract_version(row):
    for text in (row['series_info'], row['subtitle']):
        if isinstance(text, str):
            m = version_pat.search(text)
            if m:
                return int(m.group(1))
    return None

df['version_number'] = df.apply(extract_version, axis=1)

import unicodedata

def normalize_text(text):
    if not isinstance(text, str):
        return None
    text = unicodedata.normalize('NFKC', text)
    text = text.replace('’', "'").replace('‘', "'")
    text = text.lower()
    text = re.sub(r"[^a-z0-9\s'\-]", ' ', text)   # buang tanda baca, sisakan ' dan -
    text = re.sub(r'\s+', ' ', text).strip()
    return text

df['main_title_clean'] = df['main_title'].apply(normalize_text)
df['subtitle_clean'] = df['subtitle'].apply(normalize_text)

