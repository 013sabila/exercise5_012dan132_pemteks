import numpy as np
import matplotlib.pyplot as plt
from sklearn.decomposition import PCA

def plot_embedding(model, ax, title, top_n=40):
    words = model.wv.index_to_key[:top_n]
    vecs = np.array([model.wv[w] for w in words])

    coords = PCA(n_components=2, random_state=42).fit_transform(vecs)

    ax.scatter(coords[:, 0], coords[:, 1], alpha=0.7)
    for w, (x, y) in zip(words, coords):
        ax.annotate(w, (x, y), fontsize=9, xytext=(3, 3), textcoords='offset points')

    ax.set_title(title)
    ax.set_xlabel('PC 1')
    ax.set_ylabel('PC 2')
    ax.grid(alpha=0.3)

fig, axes = plt.subplots(1, 2, figsize=(16, 7))
plot_embedding(w2v, axes[0], 'Word2Vec (Skip-gram) - PCA')
plot_embedding(ft, axes[1], 'FastText (Skip-gram) - PCA')
plt.tight_layout()
plt.show()

